const dictionaries = new Map<TranslationTargetLocale, readonly DictionaryEntry[]>()
const exactDictionaries = new Map<TranslationTargetLocale, ReadonlyMap<string, string>>()

for (const locale of ['en', 'de', 'es', 'pt', 'ar', 'he', 'ko'] as const) {
  const entries = new Map<string, string>()
  const sourceMessages = messages['zh-CN']
  const targetMessages = messages[locale]

  for (const key of Object.keys(sourceMessages) as Array<keyof typeof sourceMessages>) {
    const source = sourceMessages[key]
    const target = targetMessages[key]
    if (
      typeof source === 'string' &&
      typeof target === 'string' &&
      source.trim() &&
      source !== target
    ) {
      entries.set(source, target)
    }
  }

  for (const [source, target] of domainEntries[locale]) entries.set(source, target)

  const ordered = [...entries.entries()]
    .filter(([source, target]) => source.trim() && target.trim())
    .sort(([left], [right]) => right.length - left.length)
  dictionaries.set(locale, ordered)
  exactDictionaries.set(locale, new Map(ordered))
}

const hanCharacter = /[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]/u

function preserveWhitespace(source: string, text: string) {
  const leading = source.match(/^\s*/u)?.[0] || ''
  const trailing = source.match(/\s*$/u)?.[0] || ''
  return `${leading}${text}${trailing}`
}

function replaceTerms(source: string, entries: readonly DictionaryEntry[]) {
  let cursor = 0
  let matchedTerms = 0
  let result = ''

  while (cursor < source.length) {
    const entry = entries.find(([term]) => source.startsWith(term, cursor))
    if (!entry) {
      result += source[cursor]
      cursor += 1
      continue
    }

    result += entry[1]
    cursor += entry[0].length
    matchedTerms += 1
  }

  return { matchedTerms, text: result }
}

export function translateWithDictionary(
  source: string,
  target: TranslationTargetLocale,
): DictionaryTranslation {
  if (!source.trim()) return { matchedTerms: 0, partial: false, text: source }

  const body = source.trim()
  const exact = exactDictionaries.get(target)?.get(body)
  if (exact) {
    return {
      matchedTerms: 1,
      partial: hanCharacter.test(exact),
      text: preserveWhitespace(source, exact),
    }
  }

  const result = replaceTerms(source, dictionaries.get(target) || [])
  return {
    matchedTerms: result.matchedTerms,
    partial: hanCharacter.test(result.text),
    text: result.text,
  }
}
